# chart.py
# 박자(BPM)와 노트 패턴을 정하는 파일
# 음악(sound_maker.py)과 판정(game_logic.py)이 모두 이 파일의 값을 사용하므로
# 음악의 박자와 노트 타이밍이 항상 같은 기준으로 맞춰진다.

BPM = 144                 # 1분에 144박
BEAT = 60 / BPM           # 한 박의 길이(초) = 약 0.4167초
BAR = BEAT * 4            # 한 마디(4박) = 약 1.667초

# 구간 시간(초) - BPM 144에서는 모두 마디의 시작과 정확히 일치한다
TENSION_TIME = 10.0       # 6마디 시작: 공연 직전 긴장감
REVERSE_TIME = 15.0       # 9마디 시작: 돌발 상황(규칙 반전)
FEVER_TIME = 25.0         # 15마디 시작: 피버 타임
GAME_LENGTH = 30.0        # 18마디 끝: 게임 종료

# 레인 번호: 0=←  1=↓  2=↑  3=→
LANE_NAMES = ["←", "↓", "↑", "→"]


def opposite_lane(lane):
    """반대 방향 레인 (← ↔ →, ↓ ↔ ↑)"""
    return 3 - lane


