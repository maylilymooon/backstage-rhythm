def beat_to_time(beat):
    return beat * BEAT


def section_at(t):
    """시간 t(초)의 구간 이름"""
    if t < TENSION_TIME:
        return "rehearsal"
    if t < REVERSE_TIME:
        return "tension"
    if t < FEVER_TIME:
        return "reverse"
    return "fever"


def is_reversed_at(t):
    return t >= REVERSE_TIME
